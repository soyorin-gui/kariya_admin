package org.lbl.agent.core.model;

/**
 * 工具返回内容的"形态"，前端据此决定用哪种渲染器显示。
 * <p>
 * 这是多能力平台的关键：不同的能力输出形态完全不同（对比=表格、文档=文件、血缘=图），
 * 让工具自己声明形态，agent 框架和前端才能对它们一视同仁地处理，而不必为每个能力写死分支。
 */
public enum ContentKind {
    /** 纯文本结论（日志排查等）。 */
    TEXT,
    /** 结构化对比结果，前端用表格/差异视图渲染。 */
    DIFF,
    /** 生成的文件（Word 等），payload 里带下载 token/文件名。 */
    FILE,
    /** 图结构（血缘分析等），前端用 G6 渲染。 */
    GRAPH
}
